"""Generate main/mel_matrix_sparse_col.h from tf.signal.linear_to_mel_weight_matrix.

Usage (defaults match main/mel_matrix.h):
    python tools/gen_mel_sparse.py
    python tools/gen_mel_sparse.py --fft-length 512 --num-mel-bins 64 \
        --sample-rate 16000 --lower-edge 125 --upper-edge 7600

The mel parameters MUST be identical to the ones in your training frontend.
"""
import argparse
from pathlib import Path

import numpy as np
import tensorflow as tf


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--fft-length", type=int, default=512)
    ap.add_argument("--num-mel-bins", type=int, default=64)
    ap.add_argument("--sample-rate", type=int, default=16000)
    ap.add_argument("--lower-edge", type=float, default=125.0)
    ap.add_argument("--upper-edge", type=float, default=7600.0)
    ap.add_argument("--out", type=Path,
                    default=Path(__file__).resolve().parent.parent / "main" / "mel_matrix_sparse_col.h")
    a = ap.parse_args()

    num_bins = a.fft_length // 2 + 1  # tf.signal.stft output bins
    mel = tf.signal.linear_to_mel_weight_matrix(
        num_mel_bins=a.num_mel_bins,
        num_spectrogram_bins=num_bins,
        sample_rate=a.sample_rate,
        lower_edge_hertz=a.lower_edge,
        upper_edge_hertz=a.upper_edge,
    ).numpy().astype(np.float32)  # shape (num_bins, num_mel_bins)

    entries, offsets, lengths = [], [], []
    for m in range(a.num_mel_bins):
        rows = np.nonzero(mel[:, m])[0]
        offsets.append(len(entries))
        lengths.append(len(rows))
        entries.append([(int(r), float(mel[r, m])) for r in rows])
    total = sum(lengths)
    assert total < 65536, "offsets are uint16_t"

    L = [
        "#pragma once", "",
        '#include "mel_matrix.h"', "",
        "// GENERATED by tools/gen_mel_sparse.py - do not edit by hand.",
        f"// tf.signal.linear_to_mel_weight_matrix(num_mel_bins={a.num_mel_bins}, "
        f"num_spectrogram_bins={num_bins}, sample_rate={a.sample_rate}, "
        f"lower_edge_hertz={a.lower_edge}, upper_edge_hertz={a.upper_edge})",
        "// Sparse mel filterbank matrix stored in column format.",
        "// Each column contains pairs of (row_index, value) for non-zero entries.", "",
        f"static constexpr uint16_t g_mel_matrix_sparse_col_num_rows = {num_bins};",
        f"static constexpr uint16_t g_mel_matrix_sparse_col_num_cols = {a.num_mel_bins};",
        "static_assert(g_mel_matrix_sparse_col_num_rows == LOGMEL_NUM_SPECTROGRAM_BINS, "
        '"update mel_matrix.h defines");',
        "static_assert(g_mel_matrix_sparse_col_num_cols == LOGMEL_NUM_MEL_BINS, "
        '"update mel_matrix.h defines");', "",
        "struct MelMatrixEntry {", "  uint16_t row_idx;", "  float value;", "};", "",
        "static constexpr MelMatrixEntry g_mel_matrix_sparse_cols[] = {",
    ]
    for m, col in enumerate(entries):
        L.append(f"  // Column {m}")
        L += [f"  {{{r}, {v:.8f}f}}," for r, v in col]
    L += ["};", "", "static constexpr uint16_t g_mel_matrix_sparse_col_offsets[] = {"]
    L += [f"  {o},  // Column {m}" for m, o in enumerate(offsets)]
    L += ["};", "", "static constexpr uint16_t g_mel_matrix_sparse_col_lengths[] = {"]
    L += [f"  {n},  // Column {m}" for m, n in enumerate(lengths)]
    L += ["};", ""]
    a.out.write_text("\n".join(L), encoding="utf-8")
    print(f"wrote {a.out}: dense {mel.shape}, {total} non-zeros")


if __name__ == "__main__":
    main()
